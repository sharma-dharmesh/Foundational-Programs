"""Use trunc(), floor() and ceil() for numbers -2.8, -0.5, 0.2, 1.5 and 2.9 to understand the difference between those functions clearly."""

import math

print("Trunc:")
print(math.trunc(-2.8))
print(math.trunc(-0.5))
print(math.trunc(0.2))
print(math.trunc(1.5))
print(math.trunc(2.9))

print("\nfloor:")
print(math.floor(-2.8))
print(math.floor(-0.5))
print(math.floor(0.2))
print(math.floor(1.5))
print(math.floor(2.9))

print("\nceil:")
print(math.ceil(-2.8))
print(math.ceil(-0.5))
print(math.ceil(0.2))
print(math.ceil(1.5))
print(math.ceil(2.9))
