"""Write a program that makes use of functions to the math module."""

# mathematical functions from math module
import math

x = 34.55

print(math.pi, math.e)
print(math.sqrt(x))
print(math.factorial(5))
print(math.fabs(x))
print(math.log(x))
print(math.log10(x))
print(math.exp(x))
print(math.trunc(x))
print(math.floor(x))
print(math.ceil(x))
print(math.trunc(-x))
print(math.floor(-x))
print(math.ceil(-x))
print(math.modf(x))